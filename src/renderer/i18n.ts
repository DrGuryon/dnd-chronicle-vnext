let currentLocale: ApplicationLocale = 'cs';

export function setApplicationLocale(locale: string): ApplicationLocale {
  currentLocale = locale.toLowerCase().startsWith('en') ? 'en' : 'cs';
  document.documentElement.lang = currentLocale;
  return currentLocale;
}

export function getApplicationLocale(): ApplicationLocale { return currentLocale; }

export function t(key: TranslationKey, values: Record<string, string | number> = {}): string {
  const template = (currentLocale === 'en' ? en : cs)[key];
  return Object.entries(values).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template,
  );
}

export function languageName(locale: string): string {
  const normalized = locale.toLowerCase();
  if (normalized === 'cs' || normalized === 'cz') return currentLocale === 'en' ? 'Czech (CZ)' : 'Čeština (CZ)';
  if (normalized === 'en') return currentLocale === 'en' ? 'English (EN)' : 'Angličtina (EN)';
  try {
    return new Intl.DisplayNames([currentLocale], { type: 'language' }).of(normalized) ?? locale.toUpperCase();
  } catch {
    return locale.toUpperCase();
  }
}
