function markdownGoblinWarrior() {
  const block = markdownHeading(markdownMonsters, 'Goblin Warrior');
  const text = cleanMarkdown(block);
  const identity = block.match(/^\s*_([^,]+),\s*([^_]+)_/m);
  const field = (label) => cleanMarkdown(block.match(new RegExp(`\\*\\*${label}\\*\\*\\s*([^<\\n]+)`, 'i'))?.[1] ?? '');
  const actions = [...block.matchAll(/\*\*_([^*]+)\.\*\*\s*([^\n<]+)/g)].map((match) => `${cleanMarkdown(match[1])}: ${cleanMarkdown(match[2])}`);
  return {
    name: 'Goblin Warrior', size: identity?.[1]?.split(/\s+/)[0] ?? '', type: identity?.[1]?.split(/\s+/).slice(1).join(' ') ?? '',
    alignment: identity?.[2] ?? '', armor_class: field('AC'), hit_points: field('HP'), speed: field('Speed'),
    skills: field('Skills'), gear: field('Gear'), senses: field('Senses'), languages: field('Languages'), challenge_rating: field('CR'),
    desc: [identity?.[0] ? cleanMarkdown(identity[0]) : '', ...actions, text].filter(Boolean),
    sourceReference: 'Monsters A-Z · Goblins · Goblin Warrior',
  };
}

function factsFor(type, record) {
  const result = [];
  const add = (key, value) => { const rendered = render(value); if (rendered) result.push({ key, value: rendered }); };
  if (type === 'Spell') {
    add('level', record.level); add('school', record.school?.name ?? record.school);
    add('castingTime', record.casting_time); add('range', record.range); add('components', record.components);
    add('duration', record.duration); add('concentration', record.concentration ? 'Yes' : 'No'); add('ritual', record.ritual ? 'Yes' : 'No');
    add('savingThrow', record.dc?.dc_type?.name); add('attackType', record.attack_type); add('damageOrHealing', spellEffect(record));
  } else if (type === 'Class') {
    add('primaryAbilities', record.primary_ability?.desc ?? record.primary_ability); add('hitDie', `d${record.hit_die}`);
    add('savingThrows', record.saving_throws); add('proficiencies', record.proficiencies);
  } else if (type === 'Species') {
    add('creatureType', record.type ?? 'Humanoid'); add('size', speciesSize(record)); add('speed', record.speed ? `${record.speed} ft` : '');
    add('traits', record.traits); add('languages', record.languages);
  } else if (type === 'Weapon') {
    add('category', record.weapon_category ?? record.equipment_categories); add('damage', record.damage?.damage_dice); add('damageType', record.damage?.damage_type);
    add('properties', record.properties); add('mastery', record.mastery); add('cost', record.cost); add('weight', record.weight ? `${record.weight} lb` : '');
  } else if (type === 'Armor') {
    add('category', record.armor_category ?? record.equipment_categories); add('armorClass', record.armor_class?.base);
    add('strength', record.str_minimum); add('stealth', record.stealth_disadvantage ? 'Disadvantage' : 'Normal'); add('cost', record.cost); add('weight', record.weight ? `${record.weight} lb` : '');
  } else {
    const candidates = [
      ['parentClass', record.class], ['category', record.type ?? record.equipment_category ?? record.equipment_categories],
      ['ability', record.ability_score ?? record.ability_scores ?? record.ability], ['prerequisite', record.prerequisites],
      ['proficiencies', record.proficiencies ?? record.starting_proficiencies], ['languages', record.languages],
      ['script', record.script], ['typicalSpeakers', record.typical_speakers], ['isRare', typeof record.is_rare === 'boolean' ? (record.is_rare ? 'Yes' : 'No') : ''],
      ['feat', record.feat], ['traits', record.traits ?? record.racial_traits], ['cost', record.cost], ['weight', record.weight],
      ['size', record.size], ['creatureType', record.type], ['armorClass', record.armor_class], ['hitPoints', record.hit_points],
      ['speed', record.speed], ['challengeRating', record.challenge_rating], ['contents', record.equipment?.length],
    ];
    for (const [key, value] of candidates) add(key, value);
    if (!result.length) add('effect', proseFor(record)[0]);
  }
  if (!result.length) add('sourceEntry', record.name);
  return result;
}

function typedContentFor(type, record, facts) {
  const sections = proseFor(record).length ? [{ id: 'description', title: 'Description', paragraphs: proseFor(record) }] : undefined;
  if (type === 'Spell') return {
    kind: 'Spell', level: Number(record.level), school: record.school?.name ?? record.school,
    castingTime: record.casting_time, range: record.range, components: record.components,
    duration: record.duration, concentration: Boolean(record.concentration), ritual: Boolean(record.ritual),
    savingThrow: record.dc?.dc_type?.name || null, attackType: record.attack_type || null,
    damageOrHealing: spellEffect(record) || null, ...(sections ? { sections } : {}),
  };
  if (type === 'Weapon') return {
    kind: 'Weapon', category: render(record.weapon_category ?? record.equipment_categories),
    damage: record.two_handed_damage ? `${record.damage.damage_dice} (${record.two_handed_damage.damage_dice} versatile)` : record.damage.damage_dice,
    damageType: render(record.damage.damage_type), properties: names(record.properties), mastery: render(record.mastery) || null,
    cost: render(record.cost) || null, weight: record.weight ? `${record.weight} lb` : null, ...(sections ? { sections } : {}),
  };
  if (type === 'Armor') return {
    kind: 'Armor', category: render(record.armor_category ?? record.equipment_categories), armorClass: String(record.armor_class.base),
    strength: record.str_minimum ? String(record.str_minimum) : null, stealth: record.stealth_disadvantage ? 'Disadvantage' : 'Normal',
    cost: render(record.cost) || null, weight: record.weight ? `${record.weight} lb` : null,
    don: record.don_time ?? null, doff: record.doff_time ?? null, ...(sections ? { sections } : {}),
  };
  if (type === 'Species') return {
    kind: record.speed && typeof record.speed === 'number' && record.type ? 'Species' : 'Race',
    size: speciesSize(record), speed: record.speed ? `${record.speed} ft` : 'See description',
    creatureType: record.type ?? 'Humanoid', senses: names(record.traits).filter((value) => /sense|vision/i.test(value)),
    defenses: names(record.traits).filter((value) => /resilien|ancestry|resistance/i.test(value)), languages: names(record.languages),
    ...(sections ? { sections } : {}),
  };
  if (type === 'Class') return {
    kind: 'Class', hitDie: `d${record.hit_die}`, primaryAbilities: names(record.primary_ability?.ability_scores).length
      ? names(record.primary_ability.ability_scores) : [render(record.primary_ability?.desc) || 'See class description'],
    savingThrows: names(record.saving_throws), armorTraining: names(record.proficiencies).filter((value) => /armor|shield/i.test(value)),
    weaponProficiencies: names(record.proficiencies).filter((value) => /weapon|sword|bow|crossbow|club|dagger|dart|sling/i.test(value)).concat(
      names(record.proficiencies).some((value) => /weapon|sword|bow|crossbow|club|dagger|dart|sling/i.test(value)) ? [] : ['See class proficiencies'],
    ), ...(sections ? { sections } : {}),
  };
  return { kind: 'Generic', definitionType: type, facts, ...(sections ? { sections } : {}) };
}

function proseFor(record) {
  return [record.summary, record.description, record.desc, record.size_description, record.language_desc,
    record.subclass_flavor, record.note, record.feature?.desc]
    .flatMap((value) => Array.isArray(value) ? value : value ? [value] : [])
    .map((value) => cleanMarkdown(String(value))).filter(Boolean);
}

function spellEffect(record) {
  const damage = record.damage?.damage_at_slot_level ?? record.damage?.damage_at_character_level;
  const healing = record.heal_at_slot_level;
  const values = damage ?? healing;
  if (values && typeof values === 'object') {
    const first = Object.entries(values)[0];
    if (first) return `${first[1]}${record.damage?.damage_type?.name ? ` ${record.damage.damage_type.name}` : healing ? ' healing' : ''}`;
  }
  const prose = proseFor(record).join(' ');
  const typedDamage = prose.match(/\b(\d+d\d+(?:\s*\+\s*\d+)?)\s+(Acid|Bludgeoning|Cold|Fire|Force|Lightning|Necrotic|Piercing|Poison|Psychic|Radiant|Slashing|Thunder)\s+damage\b/i);
  if (typedDamage) return `${typedDamage[1]} ${typedDamage[2]}`;
  const dice = [...prose.matchAll(/\b\d+d\d+(?:\s*\+\s*\d+)?\b/gi)].map((match) => match[0]);
  for (const match of prose.matchAll(/\ba d(\d+)\b/gi)) dice.push(`1d${match[1]}`);
  return [...new Set(dice)].join(', ');
}

function render(value) {
  if (value === null || value === undefined || value === '') return '';
  if (typeof value === 'string' || typeof value === 'number') return String(value);
  if (Array.isArray(value)) return value.map(render).filter(Boolean).join(', ');
  if (typeof value === 'object') {
    if (value.name) return String(value.name);
    if (value.quantity !== undefined && value.unit) return `${value.quantity} ${value.unit}`;
    if (value.desc) return render(value.desc);
    return Object.entries(value).filter(([key]) => key !== 'url' && key !== 'index')
      .map(([key, nested]) => `${humanize(key)}: ${render(nested)}`).filter((item) => !item.endsWith(': ')).join(', ');
  }
  return '';
}

function names(value) { return Array.isArray(value) ? value.map(render).filter(Boolean) : value ? [render(value)] : []; }
function speciesSize(record) {
  const options = record.size_options?.from?.options?.map((option) => option.size).filter(Boolean) ?? [];
  return render(record.size ?? record.size_description) || options.join(' or ') || render(record.size_options?.desc);
}
function factDescription(facts) { return facts.map((fact) => `${humanize(fact.key)}: ${fact.value}.`).join(' '); }
function englishDescription(name, type, facts, prose) {
  const sourceText = prose.length ? prose.join('\n\n') : factDescription(facts);
  if (type === 'Language') {
    const rarity = facts.find((fact) => fact.key === 'isRare')?.value === 'Yes' ? 'rare' : 'standard';
    return `${name} is listed as a ${rarity} language in this SRD ruleset. ${sourceText}`;
  }
  if (type === 'DamageType') return `${name} damage is represented in the SRD by these examples: ${sourceText}.`;
  if (type === 'Skill') return `The ${name} skill is used to ${sourceText.replace(/^[A-Z]/, (letter) => letter.toLocaleLowerCase('en-US'))}`;
  if (type === 'WeaponCategory') return `${name} contains ${facts.find((fact) => fact.key === 'contents')?.value ?? 'the listed'} weapon entries in this SRD ruleset.`;
  if (sourceText.length > 40) return sourceText;
  return `${name} is defined by the following sourced rules data: ${sourceText}`;
}
function shortText(value) {
  const clean = cleanMarkdown(value).replace(/\s+/g, ' ').trim();
  if (!clean) return '';
  // A teaser is a complete sentence, never an arbitrary character slice.
  // This also keeps list rows useful without duplicating a multi-paragraph detail.
  const sentences = clean.match(/[^.!?]+[.!?]+(?=\s|$)/g) ?? [];
  if (!sentences.length) return `${clean.replace(/[,:;\s]+$/, '')}.`;
  let teaser = '';
  for (const sentence of sentences) {
    teaser = `${teaser} ${sentence.trim()}`.trim();
    if (teaser.length >= 40) break;
  }
  return teaser;
}
function cleanMarkdown(value) { return value.replace(/<[^>]+>/g, ' ').replace(/[*_`#]/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/\s+/g, ' ').trim(); }
function humanize(value) { return value.replace(/([a-z])([A-Z])/g, '$1 $2').replaceAll('_', ' ').replace(/^./, (letter) => letter.toUpperCase()); }

