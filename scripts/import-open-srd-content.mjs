async function sourceRecord(version, definitionType, slug, name) {
  if (version === '2024' && definitionType === 'Spell') return markdownSpell(name);
  if (version === '2014' && definitionType === 'Rule' && slug === 'concentration') return concentration2014();
  if (version === '2024' && definitionType === 'Vehicle' && slug === 'rowboat') return markdownRowboat();
  if (version === '2024' && definitionType === 'CreatureDefinition' && slug === 'goblin') return markdownGoblinWarrior();
  const target = mapping(version, definitionType, slug);
  if (target?.markdown === 'rules') return markdownSection(markdownRules, target.heading, 'Rules Glossary');
  if (target?.markdown === 'equipment') return markdownSection(markdownEquipment, target.heading, 'Equipment');
  if (target?.markdown === 'monsters') return markdownSection(markdownMonsters, target.heading, 'Monsters A-Z');
  if (!target) throw new Error(`Chybí mapování ${version} ${definitionType}:${slug}.`);
  const records = await collection(version, target.collection);
  const record = records.find((candidate) => candidate.index === target.index);
  if (!record) throw new Error(`Zdroj neobsahuje ${version} ${target.collection}:${target.index}.`);
  return { ...record, sourceReference: target.reference ?? record.url ?? `${target.collection} · ${name}` };
}

async function concentration2014() {
  const records = await collection('2014', 'Rule-Sections');
  const casting = records.find((candidate) => candidate.index === 'casting-a-spell');
  const match = casting?.desc?.match(/#### Concentration\s*([\s\S]*?)(?=\n### Targets)/i);
  if (!match) throw new Error('SRD 5.1 neobsahuje očekávanou sekci Concentration.');
  return {
    name: 'Concentration', desc: cleanMarkdown(match[1]).split(/\n{2,}/).filter(Boolean),
    sourceReference: 'Spellcasting · Casting a Spell · Concentration',
  };
}

function mapping(version, type, slug) {
  const direct = {
    Class: 'Classes', Background: 'Backgrounds', Skill: 'Skills', Language: 'Languages',
    DamageType: 'Damage-Types', Condition: 'Conditions', Feat: 'Feats', Spell: 'Spells',
    Property: 'Weapon-Properties', Mastery: 'Weapon-Mastery-Properties',
  };
  if (type === 'Species') return { collection: version === '2014' ? 'Races' : 'Species', index: slug };
  if (type === 'Lineage') return { collection: 'Subraces', index: slug };
  if (type === 'Subclass') {
    const aliases = version === '2014'
      ? { 'life-domain': 'life', 'school-of-evocation': 'evocation', 'oath-of-devotion': 'devotion' }
      : { 'school-of-evocation': 'evoker' };
    return { collection: 'Subclasses', index: aliases[slug] ?? slug };
  }
  if (type === 'WeaponCategory') return { collection: 'Equipment-Categories', index: 'martial-melee-weapons' };
  if (['Weapon', 'Armor', 'Tool'].includes(type)) return { collection: 'Equipment', index: slug };
  if (type === 'Equipment') return { collection: 'Equipment', index: version === '2024' ? 'rope' : 'rope-hempen-50-feet' };
  if (type === 'Vehicle') return version === '2024'
    ? { markdown: 'equipment', heading: 'Rowboat', reference: 'Equipment · Mounts and Vehicles · Rowboat' }
    : { collection: 'Equipment', index: slug };
  if (type === 'CreatureDefinition') return version === '2024'
    ? { markdown: 'monsters', heading: 'Goblin Warrior', reference: 'Monsters A-Z · Goblins · Goblin Warrior' }
    : { collection: 'Monsters', index: slug };
  if (type === 'Rule') return version === '2024'
    ? { markdown: 'rules', heading: 'Concentration', reference: 'Rules Glossary · Concentration' }
    : { collection: 'Rules', index: 'spellcasting' };
  return direct[type] ? { collection: direct[type], index: slug } : undefined;
}

async function collection(version, name) {
  const key = `${version}/${name}`;
  if (!cache.has(key)) {
    const file = path.join(databaseRoot, 'src', version, 'en', `5e-SRD-${name}.json`);
    cache.set(key, JSON.parse(await readFile(file, 'utf8')));
  }
  return cache.get(key);
}

function markdownSpell(name) {
  const block = markdownHeading(markdownSpells, name);
  const lines = block.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
  const descriptor = cleanMarkdown(lines.shift() ?? '');
  const leveled = descriptor.match(/^Level\s+(\d+)\s+([A-Za-z]+)/i);
  const cantrip = descriptor.match(/^([A-Za-z]+)\s+Cantrip/i);
  const field = (...labels) => cleanMarkdown(lines.find((line) => labels.some((label) => line.startsWith(`**${label}:**`)))?.split('**').at(-1) ?? '');
  const prose = lines.filter((line) => !line.startsWith('**') && !line.startsWith('>') && !line.startsWith('<'))
    .map(cleanMarkdown).filter(Boolean);
  return {
    name,
    level: cantrip ? 0 : Number(leveled?.[1] ?? 0),
    school: cantrip?.[1] ?? leveled?.[2] ?? 'Unknown',
    casting_time: field('Casting Time'), range: field('Range'), components: field('Components', 'Component').split(',').map((item) => item.trim()),
    duration: field('Duration'), ritual: /ritual/i.test(field('Casting Time')), concentration: /concentration/i.test(field('Duration')),
    dc: { dc_type: { name: prose.join(' ').match(/(Strength|Dexterity|Constitution|Intelligence|Wisdom|Charisma) saving throw/i)?.[1] ?? '' } },
    desc: prose,
    sourceReference: `Spells · ${name}`,
  };
}

function markdownSection(source, heading, reference) {
  const block = markdownHeading(source, heading);
  const prose = block.split(/\r?\n/).map(cleanMarkdown)
    .filter((line) => line && !line.startsWith('|') && !line.startsWith('<') && !line.startsWith('>'));
  return { name: heading, desc: prose, sourceReference: reference };
}

function markdownHeading(source, heading) {
  const escaped = heading.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const headingMatch = new RegExp(`^#{2,6} ${escaped}\\s*$`, 'im').exec(source);
  if (!headingMatch) throw new Error(`Markdown neobsahuje sekci ${heading}.`);
  const contentStart = headingMatch.index + headingMatch[0].length;
  const nextHeading = /^#{2,6} .+$/m.exec(source.slice(contentStart));
  const contentEnd = nextHeading ? contentStart + nextHeading.index : source.length;
  return source.slice(contentStart, contentEnd).trim();
}

