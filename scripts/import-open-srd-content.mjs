function translateTypedContent(content, czechDescription, czechFacts) {
  const translated = structuredClone(content);
  const walk = (value) => {
    if (Array.isArray(value)) return value.map(walk);
    if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, nested]) => [key, key === 'kind' || key === 'definitionType' || key === 'id' ? nested : walk(nested)]));
    return typeof value === 'string' ? translateValue(value) : value;
  };
  const result = walk(translated);
  if (result.kind === 'Generic') result.facts = czechFacts;
  if (Array.isArray(content.sections) && content.sections.length) {
    result.sections = [{ id: 'description', title: 'Pravidlový význam', paragraphs: [czechDescription] }];
  }
  return result;
}

